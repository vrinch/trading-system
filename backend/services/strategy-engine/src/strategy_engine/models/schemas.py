# Base model with common fields
class BaseStrategyModel(BaseModel):
    """Base model for all strategy-related schemas."""
    timestamp: datetime = Field(..., description="Event timestamp in UTC")
    strategy_id: str = Field(..., description="Strategy identifier")
    
    @validator("timestamp", pre=True)
    def parse_timestamp(cls, v):
        """Convert various timestamp formats to datetime."""
        if isinstance(v, (int, float)):
            if v > 1e10:  # Milliseconds
                v = v / 1000
            return datetime.fromtimestamp(v, tz=timezone.utc)
        elif isinstance(v, str):
            return datetime.fromisoformat(v.replace('Z', '+00:00'))
        elif isinstance(v, datetime):
            if v.tzinfo is None:
                return v.replace(tzinfo=timezone.utc)
            return v.astimezone(timezone.utc)
        return v
    
    class Config:
        json_encoders = {
            datetime: lambda v: v.isoformat(),
            Decimal: str,
        }
        use_enum_values = True


class Signal(BaseStrategyModel):
    """Trading signal generated by strategy."""
    symbol: str = Field(..., description="Trading symbol")
    signal_type: SignalType = Field(..., description="Type of signal")
    side: Side = Field(..., description="Trade direction")
    strength: float = Field(..., description="Signal strength (0-1)", ge=0, le=1)
    confidence: float = Field(..., description="Signal confidence (0-1)", ge=0, le=1)
    
    # Price and sizing information
    target_price: Optional[Decimal] = Field(None, description="Target entry/exit price")
    stop_price: Optional[Decimal] = Field(None, description="Stop loss price")
    take_profit_price: Optional[Decimal] = Field(None, description="Take profit price")
    position_size: Optional[Decimal] = Field(None, description="Suggested position size")
    
    # Signal metadata
    indicators: Dict[str, float] = Field(default_factory=dict, description="Supporting indicators")
    features: Dict[str, float] = Field(default_factory=dict, description="ML features if applicable")
    reasoning: Optional[str] = Field(None, description="Human-readable reasoning")
    
    # Timing and validity
    valid_until: Optional[datetime] = Field(None, description="Signal expiration time")
    execution_horizon: Optional[int] = Field(None, description="Expected execution time in seconds")
    
    @validator("strength", "confidence")
    def validate_probabilities(cls, v):
        """Ensure probability values are valid."""
        if not 0 <= v <= 1:
            raise ValueError("Probability values must be between 0 and 1")
        return v


class Position(BaseStrategyModel):
    """Trading position representation."""
    position_id: str = Field(..., description="Unique position identifier")
    symbol: str = Field(..., description="Trading symbol")
    side: Side = Field(..., description="Position side")
    quantity: Decimal = Field(..., description="Position quantity")
    
    # Price information
    entry_price: Decimal = Field(..., description="Average entry price")
    current_price: Optional[Decimal] = Field(None, description="Current market price")
    
    # P&L tracking
    unrealized_pnl: Decimal = Field(default=Decimal('0'), description="Unrealized P&L")
    realized_pnl: Decimal = Field(default=Decimal('0'), description="Realized P&L")
    total_pnl: Optional[Decimal] = Field(None, description="Total P&L")
    
    # Cost basis and fees
    cost_basis: Decimal = Field(..., description="Total cost basis")
    commission_paid: Decimal = Field(default=Decimal('0'), description="Total commissions")
    
    # Risk metrics
    var_95: Optional[Decimal] = Field(None, description="Value at Risk 95%")
    beta: Optional[float] = Field(None, description="Beta vs benchmark")
    
    # Position management
    status: PositionStatus = Field(default=PositionStatus.OPEN, description="Position status")
    stop_loss: Optional[Decimal] = Field(None, description="Stop loss price")
    take_profit: Optional[Decimal] = Field(None, description="Take profit price")
    
    # Metadata
    opened_at: datetime = Field(..., description="Position open timestamp")
    closed_at: Optional[datetime] = Field(None, description="Position close timestamp")
    tags: List[str] = Field(default_factory=list, description="Position tags")
    
    @validator("total_pnl", always=True)
    def calculate_total_pnl(cls, v, values):
        """Auto-calculate total P&L if not provided."""
        if v is None:
            unrealized = values.get("unrealized_pnl", Decimal('0'))
            realized = values.get("realized_pnl", Decimal('0'))
            return unrealized + realized
        return v


