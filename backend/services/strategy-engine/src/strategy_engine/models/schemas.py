    win_rate: float = Field(..., description="Win rate %")
    avg_win: float = Field(..., description="Average winning trade %")
    avg_loss: float = Field(..., description="Average losing trade %")
    profit_factor: float = Field(..., description="Profit factor")
    
    # Detailed results
    daily_returns: List[float] = Field(default_factory=list, description="Daily returns")
    equity_curve: List[float] = Field(default_factory=list, description="Equity curve values")
    drawdown_series: List[float] = Field(default_factory=list, description="Drawdown series")
    trade_log: List[Dict] = Field(default_factory=list, description="Individual trade records")
    
    # Benchmark comparison
    benchmark_return: Optional[float] = Field(None, description="Benchmark total return %")
    alpha: Optional[float] = Field(None, description="Alpha vs benchmark")
    information_ratio: Optional[float] = Field(None, description="Information ratio")
    
    @validator("win_rate", pre=True, always=True)
    def calculate_win_rate(cls, v, values):
        """Calculate win rate from trade counts."""
        if v is None:
            total = values.get("total_trades", 0)
            winning = values.get("winning_trades", 0)
            return (winning / total * 100) if total > 0 else 0
        return v


